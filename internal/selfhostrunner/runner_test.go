func TestSelfhostDriverCacheKeyChangesWithInputs(t *testing.T) {
	root := t.TempDir()
	for _, dir := range []string{"cmd/rune", "core", "internal/selfhostrunner", "selfhost/interpreter"} {
		if err := os.MkdirAll(filepath.Join(root, dir), 0o755); err != nil {
			t.Fatalf("MkdirAll(%s) error = %v", dir, err)
		}
	}
	files := map[string]string{
		"go.mod":                            "module test\n",
		"go.sum":                            "",
		"cmd/rune/main.go":                  "package main\n",
		"core/string.rn":                    "value() => 1\n",
		"internal/selfhostrunner/a.go":      "package selfhostrunner\n",
		"internal/selfhostrunner/a_test.go": "package selfhostrunner\n",
		"selfhost/interpreter/main.rn":      "main() => 1\n",
		"selfhost/interpreter/notes.txt":    "ignored\n",
	}
	for name, content := range files {
		if err := os.WriteFile(filepath.Join(root, filepath.FromSlash(name)), []byte(content), 0o644); err != nil {
			t.Fatalf("WriteFile(%s) error = %v", name, err)
		}
	}

	first, err := selfhostDriverCacheKey(root)
	if err != nil {
		t.Fatalf("selfhostDriverCacheKey first error = %v", err)
	}
	if err := os.WriteFile(filepath.Join(root, "selfhost/interpreter/notes.txt"), []byte("still ignored\n"), 0o644); err != nil {
		t.Fatalf("WriteFile ignored file error = %v", err)
	}
	ignored, err := selfhostDriverCacheKey(root)
	if err != nil {
		t.Fatalf("selfhostDriverCacheKey ignored error = %v", err)
	}
	if ignored != first {
		t.Fatalf("cache key changed for ignored file: %s -> %s", first, ignored)
	}
	if err := os.WriteFile(filepath.Join(root, "internal/selfhostrunner/a_test.go"), []byte("package selfhostrunner\nfunc TestIgnored() {}\n"), 0o644); err != nil {
		t.Fatalf("WriteFile test file error = %v", err)
	}
	testFile, err := selfhostDriverCacheKey(root)
	if err != nil {
		t.Fatalf("selfhostDriverCacheKey test file error = %v", err)
	}
	if testFile != first {
		t.Fatalf("cache key changed for test file: %s -> %s", first, testFile)
	}
	if err := os.WriteFile(filepath.Join(root, "selfhost/interpreter/main.rn"), []byte("main() => 2\n"), 0o644); err != nil {
		t.Fatalf("WriteFile source file error = %v", err)
	}
	changed, err := selfhostDriverCacheKey(root)
	if err != nil {
		t.Fatalf("selfhostDriverCacheKey changed error = %v", err)
	}
	if changed == first {
		t.Fatalf("cache key did not change after source edit: %s", changed)
	}
}
