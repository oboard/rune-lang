func selfhostCompileOutput(t *testing.T, function string, source string) string {
	t.Helper()
	compilerPath := filepath.Join(repoRootForTest(t), "selfhost", "compiler", "compiler.rn")
	program := "@" + quoteRuneString(compilerPath) + "\n\nmain() => {\n  source := `" + source + "`\n  result := " + function + "(source)\n  @io.println(result.output)\n}\n"
	prog, diags := compiler.AnalyzeSource("selfhost_compile_output.rn", program)
	if len(diags) > 0 {
		t.Fatalf("AnalyzeSource diagnostics = %v\nprogram:\n%s", diags, program)
	}
	result := RunMainIR(prog.IR)
	if result.Err != nil {
		t.Fatalf("RunMainIR error = %v, output = %q", result.Err, result.Output)
	}
	return result.Output
}

