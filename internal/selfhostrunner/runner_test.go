func runTypeScriptInterpreterAPITests(t *testing.T, specs []selfhostAPITestSpec) {
	t.Helper()
	dir := t.TempDir()
	interpreterPath := filepath.Join(dir, "interpreter.ts")
	driverPath := filepath.Join(dir, "driver.ts")
	source := generatedSelfhostSourceForTest(t, "ts")
	writeTextFile(t, interpreterPath, source)
	writeTextFile(t, driverPath, typeScriptInterpreterAPIDriver(t, specs))
	writeTextFile(t, filepath.Join(dir, "package.json"), "{\"type\":\"module\"}\n")
	cmd := exec.Command("tsc", "--target", "ES2021", "--lib", "ES2021,DOM", "--module", "NodeNext", "--moduleResolution", "NodeNext", "driver.ts", "interpreter.ts")
	cmd.Dir = dir
	if out, err := cmd.CombinedOutput(); err != nil {
		if _, statErr := os.Stat(filepath.Join(dir, "driver.js")); statErr != nil {
			t.Fatalf("tsc generated interpreter API driver failed: %v\n%s", err, out)
		}
	}
	run := exec.Command("node", filepath.Join(dir, "driver.js"))
	out, err := run.CombinedOutput()
	if err != nil {
		t.Fatalf("node generated interpreter API driver failed: %v\n%s", err, out)
	}
	if strings.Contains(string(out), "__RUNE_SELFHOST_ERROR__") {
		t.Fatalf("generated TypeScript interpreter API tests failed:\n%s", out)
	}
}

