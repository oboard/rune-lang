func TestRunMainIR(t *testing.T) {
	prog, diags := compiler.AnalyzeSource("main_ir.rn", `main() => {
  @io.println("hello", 42)
}`)
	if len(diags) > 0 {
		t.Fatalf("AnalyzeSource diagnostics = %v", diags)
	}
	result := RunMainIR(prog.IR)
	if result.Err != nil {
		t.Fatalf("RunMainIR error = %v, output = %q", result.Err, result.Output)
	}
	if result.Output != "hello 42\n" {
		t.Fatalf("RunMainIR output = %q, want %q", result.Output, "hello 42\n")
	}
}

