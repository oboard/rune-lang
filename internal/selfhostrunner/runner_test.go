func runSelfhostIRTests(t *testing.T, file string, names []string) {
	t.Helper()
	path := filepath.Join("..", "..", "tests", file)
	prog, diags := compiler.AnalyzeFile(path)
	if len(diags) > 0 {
		t.Fatalf("AnalyzeFile(%s) diagnostics = %v", path, diags)
	}
	for _, name := range names {
		result := RunTestIR(prog.IR, name)
		if result.Err != nil {
			t.Fatalf("RunTestIR(%s %q) error = %v, output = %q", file, name, result.Err, result.Output)
		}
	}
}

func runSelfhostIRAllTests(t *testing.T, file string) {
	t.Helper()
	path := filepath.Join("..", "..", "tests", file)
	prog, diags := compiler.AnalyzeFile(path)
	if len(diags) > 0 {
		t.Fatalf("AnalyzeFile(%s) diagnostics = %v", path, diags)
	}
	for _, test := range prog.IR.Tests {
		result := RunTestIR(prog.IR, test.Name)
		if result.Err != nil {
			t.Fatalf("RunTestIR(%s %q) error = %v, output = %q", file, test.Name, result.Err, result.Output)
		}
	}
}

