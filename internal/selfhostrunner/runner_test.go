func typeScriptInterpreterAPIDriver(t *testing.T, specs []selfhostAPITestSpec) string {
	t.Helper()
	var b strings.Builder
	b.WriteString("import { interpretTest } from \"./interpreter.js\";\n\n")
	b.WriteString("function runCase(label: string, source: string, names: string[]): void {\n")
	b.WriteString("  for (const name of names) {\n")
	b.WriteString("    try {\n")
	b.WriteString("    const result = interpretTest(source, name);\n")
	b.WriteString("    if (!result.ok) console.log(`__RUNE_SELFHOST_ERROR__${label} ${name}: ${result.error}`);\n")
	b.WriteString("    } catch (error) {\n")
	b.WriteString("      console.log(`__RUNE_SELFHOST_ERROR__${label} ${name}: ${error instanceof Error ? error.stack : String(error)}`);\n")
	b.WriteString("    }\n")
	b.WriteString("  }\n")
	b.WriteString("}\n\n")
	for _, spec := range specs {
		b.WriteString("runCase(")
		b.WriteString(strconv.Quote(spec.file))
		b.WriteString(", ")
		b.WriteString(strconv.Quote(readTestSource(t, spec.file)))
		b.WriteString(", [")
		for i, name := range spec.names {
			if i > 0 {
				b.WriteString(", ")
			}
			b.WriteString(strconv.Quote(name))
		}
		b.WriteString("]);\n")
	}
	return b.String()
}

func moonBitInterpreterAPIDriver(t *testing.T, specs []selfhostAPITestSpec) string {
	t.Helper()
	var b strings.Builder
	b.WriteString("fn run_case(label : String, source : String, names : Array[String]) -> Unit {\n")
	b.WriteString("  names.each(fn(name) {\n")
	b.WriteString("    let result = interpretTest(source, name)\n")
	b.WriteString("    if !result.ok {\n")
	b.WriteString("      println(\"__RUNE_SELFHOST_ERROR__\" + label + \" \" + name + \": \" + result.error)\n")
	b.WriteString("    }\n")
	b.WriteString("  })\n")
	b.WriteString("}\n\n")
	b.WriteString("fn main {\n")
	for _, spec := range specs {
		b.WriteString("  run_case(")
		b.WriteString(quoteMoonBitString(spec.file))
		b.WriteString(", ")
		b.WriteString(quoteMoonBitString(readTestSource(t, spec.file)))
		b.WriteString(", [")
		for i, name := range spec.names {
			if i > 0 {
				b.WriteString(", ")
			}
			b.WriteString(quoteMoonBitString(name))
		}
		b.WriteString("])\n")
	}
	b.WriteString("}\n")
	return b.String()
}

func readTestSource(t *testing.T, file string) string {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(repoRootForTest(t), "tests", file))
	if err != nil {
		t.Fatalf("ReadFile tests/%s error = %v", file, err)
	}
	return string(data)
}

func quoteMoonBitString(value string) string {
	replacer := strings.NewReplacer(
		"\\", "\\\\",
		"\"", "\\\"",
		"\n", "\\n",
		"\r", "\\r",
		"\t", "\\t",
	)
	return "\"" + replacer.Replace(value) + "\""
}

